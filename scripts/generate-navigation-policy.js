#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const configPath = path.join(projectRoot, 'config', 'navigation-policy.json');
const runtimePath = path.join(projectRoot, 'miniprogram', 'data', 'navigationPolicy.js');
const POLICY_KEYS = [
  'schemaVersion',
  'pathDistanceTieTolerancePx',
  'turnAngleDegrees',
  'uTurnAngleDegrees',
  'minimumSpokenStepMeters',
  'distanceRoundingMeters',
  'elevatorDistanceTieToleranceMeters',
];

function requireFiniteNumber(policy, key) {
  const value = policy[key];
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`navigation policy ${key} must be a finite number`);
  }
  return value;
}

function validateNavigationPolicy(policy) {
  if (!policy || typeof policy !== 'object' || Array.isArray(policy)) {
    throw new Error('navigation policy must be an object with exactly seven keys');
  }
  const actualKeys = Object.keys(policy).sort();
  const expectedKeys = [...POLICY_KEYS].sort();
  if (
    actualKeys.length !== expectedKeys.length
    || actualKeys.some((key, index) => key !== expectedKeys[index])
  ) {
    throw new Error(`navigation policy must define exactly these keys: ${POLICY_KEYS.join(', ')}`);
  }

  for (const key of POLICY_KEYS) {
    requireFiniteNumber(policy, key);
  }
  if (policy.schemaVersion !== 1) {
    throw new Error('navigation policy schemaVersion must equal 1');
  }
  if (policy.pathDistanceTieTolerancePx < 0) {
    throw new Error('navigation policy pathDistanceTieTolerancePx must be at least 0');
  }
  if (!(policy.turnAngleDegrees > 0 && policy.turnAngleDegrees < 180)) {
    throw new Error('navigation policy turnAngleDegrees must be greater than 0 and less than 180');
  }
  if (!(policy.uTurnAngleDegrees > policy.turnAngleDegrees && policy.uTurnAngleDegrees <= 180)) {
    throw new Error('navigation policy uTurnAngleDegrees must exceed turnAngleDegrees and be at most 180');
  }
  if (policy.minimumSpokenStepMeters <= 0) {
    throw new Error('navigation policy minimumSpokenStepMeters must be greater than 0');
  }
  if (policy.distanceRoundingMeters <= 0) {
    throw new Error('navigation policy distanceRoundingMeters must be greater than 0');
  }
  if (policy.elevatorDistanceTieToleranceMeters < 0) {
    throw new Error('navigation policy elevatorDistanceTieToleranceMeters must be at least 0');
  }
}

function renderNavigationPolicy(policy) {
  validateNavigationPolicy(policy);
  const normalized = Object.fromEntries(POLICY_KEYS.map(key => [key, policy[key]]));
  return [
    "'use strict';",
    '',
    '// Auto-generated by scripts/generate-navigation-policy.js. Do not edit.',
    `module.exports = Object.freeze(${JSON.stringify(normalized, null, 2)});`,
    '',
  ].join('\n');
}

function readPolicy() {
  return JSON.parse(fs.readFileSync(configPath, 'utf8'));
}

function outputPath(argv) {
  if (argv.length === 1 && argv[0] === '--write') {
    return runtimePath;
  }
  if (argv.length === 2 && argv[0] === '--output' && argv[1]) {
    return path.resolve(argv[1]);
  }
  throw new Error(
    'Usage: node scripts/generate-navigation-policy.js --write | --output <path>'
  );
}

function main(argv) {
  const destination = outputPath(argv);
  const rendered = renderNavigationPolicy(readPolicy());
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, rendered, 'utf8');
  process.stdout.write(`Wrote ${path.relative(projectRoot, destination)}\n`);
}

if (require.main === module) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}

module.exports = {
  renderNavigationPolicy,
  validateNavigationPolicy,
};
