#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const configPath = path.join(projectRoot, 'config', 'public-destinations.json');
const outputPath = path.join(projectRoot, 'miniprogram', 'data', 'destinationPolicy.js');

function normalizeSource(content) {
  return String(content).replace(/\r\n?/g, '\n');
}

function floorNumber(route) {
  const match = String(route && route.floor || '').match(/^(\d{1,2})楼$/);
  return match ? Number(match[1]) : Number.MAX_SAFE_INTEGER;
}

function stableFloorSort(routes) {
  return routes
    .map((route, index) => ({ route, index }))
    .sort((left, right) => (
      floorNumber(left.route) - floorNumber(right.route) || left.index - right.index
    ))
    .map(item => item.route);
}

function validateConfig(config) {
  if (!config || !Array.isArray(config.excludedPatientDestinations)) {
    throw new Error('public-destinations.json must define excludedPatientDestinations');
  }
  if (!Array.isArray(config.publicDestinations) || config.publicDestinations.length !== 42) {
    throw new Error('public-destinations.json must define exactly 42 publicDestinations');
  }

  const names = config.publicDestinations.map(route => route && route.name);
  if (names.some(name => typeof name !== 'string' || !name)) {
    throw new Error('Every public destination must have a name');
  }
  if (new Set(names).size !== names.length) {
    throw new Error('Public destination names must be unique');
  }
  for (const excludedName of config.excludedPatientDestinations) {
    if (names.includes(excludedName)) {
      throw new Error('Excluded destination is still public: ' + excludedName);
    }
  }
}

function renderRuntimeConfig(config) {
  validateConfig(config);
  const normalized = {
    excludedPatientDestinations: Array.from(config.excludedPatientDestinations),
    publicDestinations: stableFloorSort(config.publicDestinations)
  };
  const serialized = JSON.stringify(normalized, null, 2);

  return [
    "'use strict';",
    '',
    '// Auto-generated by scripts/generate-runtime-config.js. Do not edit.',
    'function deepFreeze(value) {',
    "  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;",
    '  Object.keys(value).forEach(key => deepFreeze(value[key]));',
    '  return Object.freeze(value);',
    '}',
    '',
    'const policy = deepFreeze(' + serialized + ');',
    '',
    'module.exports = policy;',
    ''
  ].join('\n');
}

function readConfig() {
  return JSON.parse(fs.readFileSync(configPath, 'utf8'));
}

function main(argv) {
  if (argv.length !== 1 || !['--write', '--check'].includes(argv[0])) {
    throw new Error('Usage: node scripts/generate-runtime-config.js <--write|--check>');
  }

  const expected = renderRuntimeConfig(readConfig());
  if (argv[0] === '--write') {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, expected, 'utf8');
    process.stdout.write('Wrote ' + path.relative(projectRoot, outputPath) + '\n');
    return;
  }

  const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (normalizeSource(actual) !== normalizeSource(expected)) {
    process.stderr.write('Generated runtime config is out of date: ' + path.relative(projectRoot, outputPath) + '\n');
    process.exitCode = 1;
    return;
  }
  process.stdout.write('Runtime config is up to date\n');
}

if (require.main === module) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(error.message + '\n');
    process.exitCode = 1;
  }
}

module.exports = {
  renderRuntimeConfig,
  stableFloorSort
};
